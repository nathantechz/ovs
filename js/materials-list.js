// Render materials for download
function renderMaterialsForDownload(courseName) {
    const course = availableMaterials[courseName];
    if (!course) return '';

    let html = `
        <div class="materials-section">
            <h3>${courseName}</h3>

            ${course.lectures ? `
                <div class="material-group">
                    <h4>📺 Lectures (${course.lectures.length})</h4>
                    <div class="material-list">
                        ${course.lectures.map(lecture => `
                            <div class="material-item">
                                <span class="material-info">
                                    <i class="fas fa-video"></i>
                                    <strong>Week ${lecture.week}:</strong> ${lecture.title}
                                </span>
                                <a href="${course.folder}/${lecture.file}" download class="btn-download-small">
                                    <i class="fas fa-download"></i> Download PDF
                                </a>
                            </div>
                        `).join('')}
                    </div>
                </div>
            ` : ''}

            ${course.readings ? `
                <div class="material-group">
                    <h4>📖 Reading Notes (${course.readings.length})</h4>
                    <div class="material-list">
                        ${course.readings.map(reading => `
                            <div class="material-item">
                                <span class="material-info">
                                    <i class="fas fa-book"></i>
                                    <strong>Week ${reading.week}</strong> Reading Notes
                                </span>
                                <a href="${course.folder}/${reading.file}" download class="btn-download-small">
                                    <i class="fas fa-download"></i> Download
                                </a>
                            </div>
                        `).join('')}
                    </div>
                </div>
            ` : ''}

            ${course.notes ? `
                <div class="material-group">
                    <h4>📝 Lecture Notes (${course.notes.length})</h4>
                    <div class="material-list">
                        ${course.notes.map(note => `
                            <div class="material-item">
                                <span class="material-info">
                                    <i class="fas fa-sticky-note"></i>
                                    <strong>Week ${note.week}</strong> Lecture Notes
                                </span>
                                <a href="${course.folder}/${note.file}" download class="btn-download-small">
                                    <i class="fas fa-download"></i> Download
                                </a>
                            </div>
                        `).join('')}
                    </div>
                </div>
            ` : ''}

            ${course.practicals ? `
                <div class="material-group">
                    <h4>🔬 Practical Guides (${course.practicals.length})</h4>
                    <div class="material-list">
                        ${course.practicals.map(practical => `
                            <div class="material-item">
                                <span class="material-info">
                                    <i class="fas fa-flask"></i>
                                    ${practical.title}
                                </span>
                                <a href="${course.folder}/${practical.file}" download class="btn-download-small">
                                    <i class="fas fa-download"></i> Download
                                </a>
                            </div>
                        `).join('')}
                    </div>
                </div>
            ` : ''}

            ${course.textbook ? `
                <div class="material-group">
                    <h4>📕 Textbook Reference</h4>
                    <div class="material-item">
                        <span class="material-info">
                            <i class="fas fa-book-open"></i>
                            ${course.textbook}
                        </span>
                        <a href="${course.folder}/${course.textbook}" download class="btn-download-small">
                            <i class="fas fa-download"></i> Download
                        </a>
                    </div>
                </div>
            ` : ''}
        </div>
    `;

    return html;
}

